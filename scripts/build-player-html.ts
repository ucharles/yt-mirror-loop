/* Bundles the WebView player (src/engines/youtube/player/entry.ts) into a JS string module and assets/player.html. */
import { buildSync } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { buildPlayerHtml } from '../src/engines/youtube/player/html';

const root = join(__dirname, '..');
const out = buildSync({
  entryPoints: [join(root, 'src/engines/youtube/player/entry.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  target: 'safari15',
  minify: true,
});
const js = out.outputFiles[0].text;
writeFileSync(
  join(root, 'src/engines/youtube/player/generated.ts'),
  `// AUTO-GENERATED by scripts/build-player-html.ts — do not edit.\nexport const PLAYER_JS = ${JSON.stringify(js)};\n`,
);
mkdirSync(join(root, 'assets'), { recursive: true });
writeFileSync(join(root, 'assets/player.html'), buildPlayerHtml({ script: js }));
console.log(`player bundle: ${js.length} bytes`);
