/* Bundles the WebView player (src/engines/youtube/player/entry.ts) into a JS string module and assets/player.html. */
import { buildSync } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { buildPlayerHtml, FORCE_HLS_SCRIPT } from '../src/engines/youtube/player/html';

// Do not trigger a full Fast Refresh merely by running typecheck/tests again.
function writeIfChanged(file: string, content: string) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== content) writeFileSync(file, content);
}

const root = join(__dirname, '..');
const out = buildSync({
  entryPoints: [join(root, 'src/engines/youtube/player/entry.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  target: 'safari15',
  minify: true,
});
const js = out.outputFiles[0].text;
const version = createHash('sha256').update(js).update(FORCE_HLS_SCRIPT).digest('hex').slice(0, 12);
writeIfChanged(
  join(root, 'src/engines/youtube/player/generated.ts'),
  `// AUTO-GENERATED by scripts/build-player-html.ts — do not edit.\nexport const PLAYER_JS = ${JSON.stringify(js)};\nexport const PLAYER_VERSION = ${JSON.stringify(version)};\n`,
);
mkdirSync(join(root, 'assets'), { recursive: true });
writeIfChanged(join(root, 'assets/player.html'), buildPlayerHtml({ script: js }));
console.log(`player bundle: ${js.length} bytes`);
